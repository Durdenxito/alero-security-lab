import { chromium } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
await mkdir('docs/images', { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
await page.goto('http://127.0.0.1:4180/'); await page.locator('.account').first().waitFor();
await page.screenshot({ path: 'docs/images/alero-desktop.png', fullPage: true });
await page.getByRole('button', { name: 'Hacer una transferencia' }).click(); await page.screenshot({ path: 'docs/images/alero-transfer.png' });
await page.getByRole('button', { name: 'Cerrar', exact: true }).click();
await page.setViewportSize({ width: 390, height: 844 }); await page.screenshot({ path: 'docs/images/alero-mobile.png', fullPage: true });
await browser.close();
